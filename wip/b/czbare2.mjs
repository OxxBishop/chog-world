// Clean plates of the casino at the roulette and the slots, on a held clock: node czbare2.mjs <out> <w> <h> <dpr> [port]
import { createRequire } from 'module';
const require = createRequire('/opt/node22/lib/node_modules/');
const { chromium } = require('playwright');
const [,, out = 'shots/bz', w = '1366', h = '768', dpr = '1', port = '5173'] = process.argv;
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const mobile = +w < 700;
const page = await browser.newPage({ viewport: { width: +w, height: +h }, deviceScaleFactor: +dpr, isMobile: mobile, hasTouch: mobile });
const logs = [];
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
await page.goto(`http://localhost:${port}/?hour=21&nointro&view=casino`);
await page.waitForSelector('#loading.done', { timeout: 900000 });
await page.waitForTimeout(1500);
await page.evaluate(() => {
  localStorage.clear();
  const w = window.chogWorld;
  const traits = { Tier: 'Legendary', Eyes: 'Purple laser', Body: 'Kings Robe', Head: 'Wizard Hat', Mouth: 'Gold Tooth', Accessory: 'Fwog', Aura: 'Purple', Skin: 'Red' };
  Object.defineProperty(w.session, 'active', { configurable: true, get: () => ({ id: 1517, info: { id: 1517, name: 'Chog #1517', traits, image: '/art/1517.webp' } }) });
  w.renderer.setAnimationLoop(null);
  let now = performance.now();
  performance.now = () => now;
  const q = [];
  window.requestAnimationFrame = (cb) => (q.push(cb), q.length);
  window.__step = (n = 1) => { for (let i = 0; i < n; i++) { now += 1000 / 30; for (const cb of q.splice(0)) cb(now); w.frame(); } };
  window.__step(3);
  w.casino.play('roulette');
});
const step = (n) => page.evaluate((n) => window.__step(n), n);
await step(150);
for (const k of ['red', 'red', 'd2']) await page.evaluate((k) => document.querySelector(`.cz-q[data-k="${k}"]`)?.click(), k);
await step(60);
await page.addStyleTag({ content: '.casino-panel, .cz-edgecard, .hud, #btn-signin, .signin-btn, [class*="time"], .places, .places-toggle, #fps, .chog-chip, .tv-hud, .cz-banner { visibility: hidden !important; }' });
await step(2);
await page.screenshot({ path: `${out}-roulette.png`, timeout: 240000 });
await page.evaluate(() => window.chogWorld.casino.play('slots'));
await step(150);
await page.screenshot({ path: `${out}-slots.png`, timeout: 240000 });
console.log('done', logs.join('\n'));
await browser.close();
